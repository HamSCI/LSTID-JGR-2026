"""
Download the GIRO ionosonde characteristics used by Figure 11.

Source:   Lowell GIRO Data Center (DIDBase), Global Ionosphere Radio Observatory.
          Data are released under CC BY-NC-SA 4.0; see ../DATA_LICENSES.md and
          https://ulcar.uml.edu/DIDBase/RulesOfTheRoadForDIDBase.htm
Stations: BC840 Boulder, AU930 Austin, EG931 Eglin, AL945 Alpena, WP937 Wallops Island,
          MHJ45 Millstone Hill.
Years:    2015-2022, one request and one file per station per year.
Output:   $LSTID_DATA_DIR/giro/giro_<STATION>_<YEAR>.txt (default: giro/ next to this script),
          the text returned by DIDBase, unmodified.

Usage:
    python download_giro.py            # download files that are not already present
    python download_giro.py --force    # download every file again, replacing existing ones
    python download_giro.py --check    # download to a temporary folder and compare with the
                                       # existing files (header lines that record the request
                                       # time and requester are ignored)
    python download_giro.py --check --station BC840 --year 2018   # test a single file

Figure 11 uses foF2 (column 3) and foEs (column 13). The other characteristics are requested so
the files match the ones used for the paper.
"""

import argparse
import os
import sys
import tempfile
import time
import urllib.parse
import urllib.request

# NOTE: endpoint and parameter names have not yet been tested against the server from this
# machine; run with --check before relying on the output.
DIDBASE_URL = "https://lgdc.uml.edu/common/DIDBGetValues"

STATIONS = ["BC840", "AU930", "EG931", "AL945", "WP937", "MHJ45"]
YEARS = range(2015, 2023)
CHARACTERISTICS = ["foF2", "hmF2", "foF1", "foE", "hmE", "foEs", "fbEs", "fmin", "B0", "B1", "TEC"]
DMUF = 3000

HERE = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.environ.get("LSTID_DATA_DIR", HERE)
GIRO_DIR = os.path.join(DATA_DIR, "giro")

# Header lines that differ between otherwise identical downloads
VOLATILE_PREFIXES = ("# Generated by", "# Requested by")

RETRIES = 3
PAUSE_S = 2  # pause between requests, to be gentle on the server


def build_url(station, year):
    params = {
        "ursiCode": station,
        "charName": ",".join(CHARACTERISTICS),
        "DMUF": DMUF,
        "fromDate": f"{year}/01/01 00:00:00",
        "toDate": f"{year}/12/31 23:59:59",
    }
    return DIDBASE_URL + "?" + urllib.parse.urlencode(params)


def fetch(url):
    for attempt in range(1, RETRIES + 1):
        try:
            with urllib.request.urlopen(url, timeout=300) as resp:
                return resp.read().decode("utf-8")
        except OSError as err:
            if attempt == RETRIES:
                raise
            print(f"   attempt {attempt} failed ({err}); retrying")
            time.sleep(10 * attempt)


def looks_valid(text, station):
    return text.startswith("#") and f"URSI-Code {station}" in text


def stable_lines(text):
    return [ln for ln in text.splitlines() if not ln.startswith(VOLATILE_PREFIXES)]


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--force", action="store_true", help="replace existing files")
    mode.add_argument("--check", action="store_true", help="compare downloads with existing files")
    parser.add_argument("--station", choices=STATIONS, help="only this station")
    parser.add_argument("--year", type=int, choices=list(YEARS), help="only this year")
    args = parser.parse_args()
    stations = [args.station] if args.station else STATIONS
    years = [args.year] if args.year else YEARS

    out_dir = tempfile.mkdtemp(prefix="giro_check_") if args.check else GIRO_DIR
    os.makedirs(out_dir, exist_ok=True)
    print(f"Writing to {out_dir}")

    n_bad = 0
    for station in stations:
        for year in years:
            fname = f"giro_{station}_{year}.txt"
            path = os.path.join(out_dir, fname)
            if os.path.exists(path) and not args.force and not args.check:
                print(f"   exists, skipping: {fname}")
                continue

            print(f"   downloading: {fname}")
            text = fetch(build_url(station, year))
            if not looks_valid(text, station):
                print(f"   ERROR: unexpected response for {fname}: {text[:200]!r}")
                n_bad += 1
                continue
            with open(path, "w") as fh:
                fh.write(text)

            if args.check:
                ref = os.path.join(GIRO_DIR, fname)
                if not os.path.exists(ref):
                    print(f"   MISSING reference file: {ref}")
                    n_bad += 1
                else:
                    with open(ref) as fh:
                        same = stable_lines(fh.read()) == stable_lines(text)
                    print(f"   {'matches' if same else 'DIFFERS from'} {ref}")
                    n_bad += not same
            time.sleep(PAUSE_S)

    if n_bad:
        print(f"{n_bad} file(s) failed or differ.")
        sys.exit(1)
    print("Done.")


if __name__ == "__main__":
    main()
